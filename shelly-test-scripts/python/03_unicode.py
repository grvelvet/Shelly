# Что проверяет: вывод UTF-8 из Python (Shelly задаёт PYTHONUTF8=1 и PYTHONIOENCODING=utf-8),
#   кириллицу в аргументах (поле «Аргументы»: например «Привет из аргумента»), длинную строку (6000 символов).
# Ожидается: весь текст без искажений во встроенной панели и в отдельном окне; код 0.
#   В старой консоли Windows 10 эмодзи могут быть квадратиками (шрифт консоли).
import sys

if len(sys.argv) > 1:
    print("Аргументы: " + " | ".join(sys.argv[1:]))
print(f"stdout.encoding = {sys.stdout.encoding}")
print("Русский:     Съешь же ещё этих мягких французских булок, да выпей чаю.")
print("Українська:  Гей, хлопці, ґанок, їжак, є")
print("Ελληνικά:    Καλημέρα κόσμε")
print("Deutsch:     Größe, Übermaß, Straße")
print("中文 / 日本語: 你好，世界 / こんにちは")
print("Иврит (RTL): שלום עולם")
print("Символы:     « » „ “ — – … № € ₽ ° ± × ÷ ≠ ≤ ≥ ∞ ✓ ✗ →")
print("Эмодзи:      " + " ".join(chr(c) for c in (0x1F600, 0x1F680, 0x1F40D, 0x2705)))
print("Табуляция:   a\tб\tв\tг")
long = "Длинная-строка-" * 400
print(f"Длинная строка ({len(long)} символов):")
print(long)
print("Конец длинной строки.")
sys.exit(0)
