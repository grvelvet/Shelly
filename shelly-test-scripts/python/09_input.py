# Описание: Python input(): ввод работает только в отдельном окне
# Shelly-Icon: E765
# Shelly-Mode: window
#
# Что проверяет: во встроенном режиме stdin закрыт, input() сразу получает EOFError.
#   Строка «Shelly-Mode: window» выше: двойной щелчок запускает скрипт в отдельном окне.
# Ожидается:
#   - отдельное окно: спрашивает имя, здоровается, ждёт Enter; затем «Код выхода: 0», окно открыто;
#   - встроенный режим (меню > «Запустить»): «input() получил EOFError: ввода нет», код 3.
import sys

try:
    name = input("Как вас зовут? ")
except EOFError:
    print("input() получил EOFError: ввода нет (встроенный режим Shelly).")
    print("Запустите скрипт в отдельном окне, чтобы ввести данные.")
    sys.exit(3)
print(f"Привет, {name}!")
input("Нажмите Enter для выхода...")
sys.exit(0)
