# Описание: PyTool: вспомогательный модуль (при импорте папки снимите с него флажок)
#
# Модуль для main.py. Его имя не начинается с «_», поэтому Shelly покажет его в списке, если не скрыть.
# При импорте папки снимите флажок - он попадёт в "hidden" файла .shelly.json.
# Если всё же запустить его отдельно: печатает пример и код 0.


def banner(text: str) -> str:
    line = "=" * (len(text) + 4)
    return f"{line}\n| {text} |\n{line}"


if __name__ == "__main__":
    print("Это модуль для main.py, запускать отдельно не нужно.")
    print(banner("пример"))
