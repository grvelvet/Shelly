# Описание: Требует прав администратора (#Requires -RunAsAdministrator)
# Shelly-Icon: E8D7
#Requires -RunAsAdministrator
#
# Что проверяет: Shelly читает #Requires -RunAsAdministrator и перед запуском без прав администратора
#   предупреждает, что скрипту нужны права администратора, и предлагает запустить от администратора
#   (или «Всё равно запустить»).
# Ожидается:
#   - «Запустить от администратора» -> подтверждение, UAC, окно с текстом «Права администратора есть»;
#   - «Всё равно запустить» во встроенном режиме -> PowerShell сам отказывается запускать скрипт
#     (сообщение про #requires ... Administrator), код 1.

Write-Output "Права администратора есть, скрипт выполнился."
Write-Output ("Движок: {0} {1}" -f $PSVersionTable.PSEdition, $PSVersionTable.PSVersion)
exit 0
